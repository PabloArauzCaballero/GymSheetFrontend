const { withDangerousMod } = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

const MARKER = '# @gymsheet/fmt-consteval-fix';

/**
 * Makes the iOS build survive Xcode 26.
 *
 * React Native 0.79 (Expo SDK 53) pins `fmt` 11.0.2, and Apple's clang 21
 * enforces something earlier compilers let through: a call to a `consteval`
 * function must itself be a constant expression. fmt 11.0.2's own
 * `format-inl.h` calls `FMT_STRING(...)` from contexts that are not, so the
 * pod fails to compile and takes the whole build with it:
 *
 *   call to consteval function 'fmt::basic_format_string<...>' is not
 *   a constant expression   (fmt/format-inl.h:1391)
 *
 * `consteval` does not exist before C++20, so compiling this one pod as C++17
 * takes fmt's own detection down the pre-C++20 branch
 * (`FMT_CPLUSPLUS < 201709L` → `FMT_USE_CONSTEVAL 0`) and the compile-time
 * check degrades to fmt's runtime format-string validation. Nothing else in
 * the project changes standard; every other pod stays on C++20.
 *
 * This is a workaround with an expiry date: fmt fixed it in 11.1, and React
 * Native picks that up from 0.83.9 / Expo SDK 56. Delete this plugin — and its
 * entry in app.json — on that upgrade.
 *
 * It lives in a config plugin rather than in `ios/Podfile` because `ios/` is
 * generated by `expo prebuild` and any hand edit there is erased by the next
 * run.
 */
function withFmtConstevalFix(config) {
  return withDangerousMod(config, [
    'ios',
    (config) => {
      const podfile = path.join(config.modRequest.platformProjectRoot, 'Podfile');
      const contents = fs.readFileSync(podfile, 'utf8');

      if (contents.includes(MARKER)) return config;

      // The patch has to land *after* `react_native_post_install`, not merely
      // inside `post_install`: that helper walks every pod target and stamps
      // CLANG_CXX_LANGUAGE_STANDARD = c++20 on all of them
      // (NewArchitectureHelper.set_clang_cxx_language_standard_if_needed), so
      // anything set before it is silently overwritten.
      const hook = /react_native_post_install\([\s\S]*?\n\s*\)\n/;
      const match = contents.match(hook);
      if (!match) {
        throw new Error(
          '[with-fmt-consteval-fix] No `react_native_post_install` call found in the ' +
            'generated Podfile. The Expo/React Native template changed shape; update this ' +
            'plugin instead of skipping it, because without the patch the iOS build fails ' +
            'outright on Xcode 26.',
        );
      }

      const patch = `${match[0]}
    ${MARKER}
    installer.pods_project.targets.each do |target|
      next unless target.name == 'fmt'

      target.build_configurations.each do |build_configuration|
        build_configuration.build_settings['CLANG_CXX_LANGUAGE_STANDARD'] = 'c++17'
      end
    end
`;

      fs.writeFileSync(podfile, contents.replace(match[0], patch));
      return config;
    },
  ]);
}

module.exports = withFmtConstevalFix;
