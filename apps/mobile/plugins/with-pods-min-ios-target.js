const { withDangerousMod } = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

const MARKER = '# @gymsheet/pods-min-ios-target';
const MIN_TARGET = '15.1';

/**
 * Makes the iOS build survive Xcode 27.
 *
 * Xcode 27 only accepts deployment targets from 15.0 up, and rejects the
 * build outright when a pod declares less:
 *
 *   error: The iOS Simulator deployment target 'IPHONEOS_DEPLOYMENT_TARGET'
 *   is set to 11.0, but the range of supported deployment target versions
 *   is 15.0 to 27.0.x.
 *
 * Several pods still declare 9.0 or 11.0 (SDWebImage and friends). Raising
 * every pod target that sits below 15.0 to 15.1 — the app's own floor — is
 * safe: none of them uses an API removed after iOS 11.
 *
 * Like `with-fmt-consteval-fix`, this lives in a config plugin because
 * `ios/` is generated by `expo prebuild` and hand edits there are erased by
 * the next run, and it has to land after `react_native_post_install`.
 * Delete it once every pod in the lockfile declares 15.0 or higher.
 */
function withPodsMinIosTarget(config) {
  return withDangerousMod(config, [
    'ios',
    (config) => {
      const podfile = path.join(config.modRequest.platformProjectRoot, 'Podfile');
      const contents = fs.readFileSync(podfile, 'utf8');

      if (contents.includes(MARKER)) return config;

      const hook = /react_native_post_install\([\s\S]*?\n\s*\)\n/;
      const match = contents.match(hook);
      if (!match) {
        throw new Error(
          '[with-pods-min-ios-target] No `react_native_post_install` call found in the ' +
            'generated Podfile. The Expo/React Native template changed shape; update this ' +
            'plugin instead of skipping it, because without the patch the iOS build fails ' +
            'outright on Xcode 27.',
        );
      }

      const patch = `${match[0]}
    ${MARKER}
    installer.pods_project.targets.each do |target|
      target.build_configurations.each do |build_configuration|
        current = build_configuration.build_settings['IPHONEOS_DEPLOYMENT_TARGET']
        next if current.nil? || Gem::Version.new(current) >= Gem::Version.new('15.0')

        build_configuration.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '${MIN_TARGET}'
      end
    end
`;

      fs.writeFileSync(podfile, contents.replace(match[0], patch));
      return config;
    },
  ]);
}

module.exports = withPodsMinIosTarget;
